def _build_reverse_index() -> dict[str, tuple[str, ...]]:
    """표제어든 동의어 값이든, 조회하면 같은 그룹 전체(자기 자신 포함,
    표제어 먼저)가 나오도록 역인덱스를 한 번 구성한다."""
    index: dict[str, tuple[str, ...]] = {}
    for canonical, synonyms in _OCCUPATION_SYNONYMS.items():
        group = (canonical, *synonyms)
        for term in group:
            index[term] = group
    return index


_REVERSE_INDEX = _build_reverse_index()


def expand_occupation_keyword(keyword: str, limit: int) -> list[str]:
    """`keyword`가 표의 표제어/동의어와 정확히 일치하면 같은 그룹의 다른
    표현들을 덧붙여 돌려준다(자기 자신이 항상 맨 앞). 일치하지 않으면
    `[keyword]`만 돌려줘 — 매핑 안 된 입력에 대해 오늘과 동일한 동작을
    자동으로 보장한다."""
    group = _REVERSE_INDEX.get(keyword)
    if group is None:
        return [keyword]
    ordered = [keyword, *[term for term in group if term != keyword]]
    return ordered[:limit]
